exec python3 -c "$(sed "1,/^: <<'PYTHON'$/d; \$d" "${BASH_SOURCE[0]}")" "$root" "$@"
: <<'PYTHON'
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import tomllib

MARKER = '# Generated by scripts/core-patch.sh; local core override.'
SOURCE = 'https://github.com/unemu-org/unemupc'
CORE = re.compile(r'^git\+(?:[a-z][a-z0-9+.-]*://)?(?:[^/@]+@)?github\.com[:/]unemu-org/unemupc(?:\.git)?(?:[/?#]|$)', re.I)


def fail(message):
    raise ValueError(message)


def active(root):
    for relative in ['.cargo/config.toml', '.cargo/config', 'Cargo.toml']:
        config = root / relative
        if config.is_file():
            patches = tomllib.loads(config.read_text()).get('patch', {})
            if any(CORE.match('git+' + source) and packages for source, packages in patches.items()):
                return relative
    return None


def apply(root, arguments):
    config = root / '.cargo/config.toml'
    if config.parent.is_symlink() or config.is_symlink():
        fail('refusing a symlink at .cargo or .cargo/config.toml')
    if config.exists() and config.read_text().splitlines()[:1] != [MARKER]:
        fail('refusing to replace or remove an unmarked .cargo/config.toml')
    if arguments == ['--remove']:
        config.unlink(missing_ok=True)
        return
    if len(arguments) != 1 or arguments[0].startswith('--'):
        fail('usage: bash scripts/core-patch.sh <unemupc checkout> | --remove | --self-test')
    checkout = Path(arguments[0]).resolve(strict=True)
    lock = tomllib.loads((root / 'Cargo.lock').read_text())
    names = sorted({p['name'] for p in lock.get('package', []) if CORE.match(p.get('source', ''))})
    if not names and config.exists():
        # Cargo removes git sources from patched lock entries. The marked
        # config retains the exact package set when switching checkouts.
        previous = tomllib.loads(config.read_text()).get('patch', {}).get(SOURCE, {})
        locked_paths = {p['name'] for p in lock.get('package', []) if 'source' not in p}
        names = sorted(set(previous) & locked_paths)
        if set(names) != set(previous):
            fail('marked .cargo/config.toml does not match the locked path packages')
    if not names:
        fail('Cargo.lock contains no unemupc git packages or marked local override')
    workspace = tomllib.loads((checkout / 'Cargo.toml').read_text())['workspace']
    packages = {}
    # Package names and directory names need not agree; Cargo's workspace
    # members, not a duplicated package table, locate the local manifests.
    excluded = {p.resolve() for pattern in workspace.get('exclude', []) for p in checkout.glob(pattern)}
    for pattern in workspace['members']:
        for directory in sorted(checkout.glob(pattern)):
            if directory.resolve() in excluded:
                continue
            manifest = directory / 'Cargo.toml'
            package = tomllib.loads(manifest.read_text()).get('package', {})
            name = package.get('name')
            if name in names:
                if name in packages:
                    fail(f'duplicate local package: {name}')
                packages[name] = directory.resolve()
    missing = sorted(set(names) - packages.keys())
    if missing:
        fail('checkout is missing locked core packages: ' + ', '.join(missing))
    text = MARKER + '\n[patch.' + json.dumps(SOURCE) + ']\n'
    for name in names:
        text += json.dumps(name) + ' = { path = ' + json.dumps(str(packages[name])) + ' }\n'
    config.parent.mkdir(exist_ok=True)
    # A failed validation must leave any previous override intact.
    with tempfile.NamedTemporaryFile(mode='w', dir=config.parent, delete=False) as output:
        temporary = Path(output.name)
        output.write(text)
    try:
        temporary.replace(config)
    finally:
        temporary.unlink(missing_ok=True)
    print(f'core-patch: wrote {len(names)} package overrides to .cargo/config.toml')


def self_test(script):
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp).resolve() / 'frontend'
        (root / 'scripts').mkdir(parents=True)
        copy = root / 'scripts/core-patch.sh'
        copy.write_text(script.read_text())
        checkout = Path(tmp).resolve() / 'core "local"'
        checkout.mkdir()
        (checkout / 'Cargo.toml').write_text('[workspace]\nmembers = ["crates/*"]\n')
        for directory, name in [('first', 'core-a'), ('second', 'core-b'), ('unused', 'testkit')]:
            p = checkout / 'crates' / directory
            p.mkdir(parents=True)
            (p / 'Cargo.toml').write_text(f'[package]\nname = "{name}"\n')
        lock = ''.join(f'[[package]]\nname = "{name}"\nsource = "git+{SOURCE}?rev=pin#pin"\n'
                       for name in ['core-b', 'core-a'])
        (root / 'Cargo.lock').write_text(lock)
        config = root / '.cargo/config.toml'
        count = 0
        def run(args, succeeds=True):
            nonlocal count
            result = subprocess.run(['bash', str(copy), *args], text=True, capture_output=True)
            assert (result.returncode == 0) == succeeds, (args, result.stdout, result.stderr)
            if not succeeds:
                assert 'core-patch:' in result.stderr
            count += 1
        run([str(checkout)])
        parsed = tomllib.loads(config.read_text())['patch'][SOURCE]
        assert sorted(parsed) == ['core-a', 'core-b']
        assert parsed['core-a']['path'] == str(checkout / 'crates/first')
        run([str(checkout)])
        # This is the source-free shape Cargo writes after applying a patch.
        (root / 'Cargo.lock').write_text('version = 4\n' + ''.join(
            f'[[package]]\nname = "{name}"\nversion = "0.0.3"\n' for name in ['core-a', 'core-b']))
        run([str(checkout)])
        other = Path(tmp).resolve() / 'other-core'
        import shutil
        shutil.copytree(checkout, other)
        run([str(other)])
        assert tomllib.loads(config.read_text())['patch'][SOURCE]['core-a']['path'] == str(other / 'crates/first')
        run([str(checkout)])
        assert active(root) == '.cargo/config.toml'
        original = config.read_text()
        (checkout / 'crates/first/Cargo.toml').write_text('[package]\nname = "other"\n')
        run([str(checkout)], False)
        assert config.read_text() == original
        run(['--remove'])
        assert not config.exists()
        run(['--remove'])
        config.write_text('# user config\n')
        run([str(checkout)], False)
        run(['--remove'], False)
        assert config.read_text() == '# user config\n'
        config.unlink()
        config.symlink_to(root / 'Cargo.lock')
        run(['--remove'], False)
        config.unlink()
        (root / 'Cargo.lock').write_text('version = 4\n')
        run([str(checkout)], False)
        run([] , False)
        assert not config.exists()
        print(f'core-patch: self-test passed ({count} cases; lock-derived names, paths, quoting, preservation and removal)')


try:
    root = Path(sys.argv[1])
    arguments = sys.argv[2:]
    if arguments == ['--active']:
        override = active(root)
        if not override:
            sys.exit(1)
        print(override)
    elif arguments == ['--self-test']:
        self_test(root / 'scripts/core-patch.sh')
    else:
        apply(root, arguments)
except (ValueError, OSError, KeyError) as error:
    print(f'core-patch: {error}', file=sys.stderr)
    sys.exit(1)
PYTHON
